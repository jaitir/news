def resolve_source_profile(
    *,
    source_name: str | None,
    url: str | None,
    handle: str | None = None,
    country_hint: str | None = None,
) -> dict | None:
    name = _normalize_text(source_name or "")
    domain = _extract_domain(url or "")
    normalized_handle = (handle or "").strip().lower().lstrip("@")

    if normalized_handle:
        handle_map = _handle_map()
        if normalized_handle in handle_map:
            return SourceProfileMatch(
                profile=handle_map[normalized_handle],
                match_type="handle",
                matched_value=normalized_handle,
            ).to_dict()

    if domain:
        domain_map = _domain_map()
        for candidate_domain, profile in domain_map.items():
            if domain == candidate_domain or domain.endswith(f".{candidate_domain}"):
                return SourceProfileMatch(
                    profile=profile,
                    match_type="domain",
                    matched_value=domain,
                ).to_dict()

    if name:
        for profile in SOURCE_REGISTRY:
            for alias in [profile.canonical_name, *profile.aliases]:
                normalized_alias = _normalize_text(alias)
                if not normalized_alias:
                    continue
                if name == normalized_alias or normalized_alias in name or name in normalized_alias:
                    return SourceProfileMatch(
                        profile=profile,
                        match_type="name",
                        matched_value=alias,
                    ).to_dict()

    return _fallback_profile(source_name=source_name, domain=domain, country_hint=country_hint)


def infer_primary_segment(profile: dict | None) -> str:
    if not profile:
        return "unknown"

    state_affinity = profile.get("state_affinity")
    geopolitical_alignment = profile.get("geopolitical_alignment")
    if state_affinity in {"state", "state_aligned", "pro_government"}:
        return "state_aligned"
    if state_affinity == "opposition":
        return "opposition"
    if geopolitical_alignment == "western":
        return "western_aligned"
    if state_affinity in {"independent", "public_service", "mixed"}:
        return "independent"
    return "unknown"


def infer_segment_tags(profile: dict | None) -> list[str]:
    if not profile:
        return ["unknown"]

    tags = {infer_primary_segment(profile)}
    state_affinity = profile.get("state_affinity")
    geopolitical_alignment = profile.get("geopolitical_alignment")

    if state_affinity in {"opposition", "independent", "public_service"}:
        tags.add("critical_non_state")
    if geopolitical_alignment == "western":
        tags.add("western_aligned")
    if state_affinity in {"state", "state_aligned", "pro_government"}:
        tags.add("state_aligned")
    return sorted(tag for tag in tags if tag)


@lru_cache
def _domain_map() -> dict[str, SourceProfile]:
    mapping: dict[str, SourceProfile] = {}
    for profile in SOURCE_REGISTRY:
        for domain in profile.domains:
            mapping[domain.lower()] = profile
    return mapping


@lru_cache
def _handle_map() -> dict[str, SourceProfile]:
    mapping: dict[str, SourceProfile] = {}
    for profile in SOURCE_REGISTRY:
        for handle in profile.handles:
            mapping[handle.lower().lstrip("@")] = profile
    return mapping


def _extract_domain(url: str) -> str:
    if not url:
        return ""
    parsed = urlparse(url if "://" in url else f"https://{url}")
    domain = (parsed.netloc or parsed.path).lower()
    return re.sub(r"^(www\.|m\.)", "", domain).strip("/")


def _normalize_text(value: str) -> str:
    normalized = re.sub(r"[^a-z0-9а-яё\u0600-\u06ff\u4e00-\u9fff]+", " ", value.lower(), flags=re.IGNORECASE)
    return " ".join(normalized.split())


def _fallback_profile(*, source_name: str | None, domain: str, country_hint: str | None) -> dict | None:
    inferred_country = normalize_country_code(country_hint) or _infer_country_from_domain(domain)
    if not inferred_country:
        return None
    canonical_name = (source_name or domain or "").strip()
    if not canonical_name:
        return None
    profile = {
        "canonical_name": canonical_name,
        "aliases": [],
        "domains": [domain] if domain else [],
        "handles": [],
        "country": inferred_country,
        "region": _infer_region(inferred_country),
        "media_class": "digital_news",
        "ownership_type": "unknown",
        "state_affinity": "mixed",
        "geopolitical_alignment": _infer_geopolitical_alignment(inferred_country),
        "confidence": 0.35,
        "notes": "Auto-inferred from country hint or domain.",
    }
    profile["match_type"] = "fallback"
    profile["matched_value"] = country_hint or domain
    profile["primary_segment"] = infer_primary_segment(profile)
    profile["segment_tags"] = infer_segment_tags(profile)
    return profile


