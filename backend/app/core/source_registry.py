@dataclass(slots=True)
class SourceProfile:
    canonical_name: str
    aliases: list[str]
    domains: list[str]
    handles: list[str] = field(default_factory=list)
    country: str | None = None
    region: str = "global"
    media_class: str = "digital_news"
    ownership_type: str = "unknown"
    state_affinity: str = "unknown"
    geopolitical_alignment: str = "unknown"
    confidence: float = 0.6
    notes: str | None = None


@dataclass(slots=True)
class SourceProfileMatch:
    profile: SourceProfile
    match_type: str
    matched_value: str

    def to_dict(self) -> dict:
        payload = asdict(self.profile)
        payload.update(
            {
                "match_type": self.match_type,
                "matched_value": self.matched_value,
                "primary_segment": infer_primary_segment(payload),
                "segment_tags": infer_segment_tags(payload),
            }
        )
        return payload


