def _infer_geopolitical_alignment(country_code: str) -> str:
    if country_code in {"US", "GB", "FR", "DE", "NL", "ES", "CA", "AU", "JP", "KR", "SG", "LV"}:
        return "western"
    return "regional"


def _infer_country_from_domain(domain: str) -> str | None:
    if not domain:
        return None
    suffix_map = {
        ".ae": "AE",
        ".az": "AZ",
        ".co.uk": "GB",
        ".com.au": "AU",
        ".com.my": "MY",
        ".com.ph": "PH",
        ".co.za": "ZA",
        ".in": "IN",
        ".jp": "JP",
        ".kr": "KR",
        ".ru": "RU",
        ".sg": "SG",
        ".tr": "TR",
    }
    for suffix, country in suffix_map.items():
        if domain.endswith(suffix):
            return country
    return None
